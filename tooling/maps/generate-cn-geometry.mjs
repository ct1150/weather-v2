import { mkdir, writeFile } from "node:fs/promises";
import { dirname } from "node:path";

const SOURCE_URL =
  "https://raw.githubusercontent.com/Supeset/China-GeoData/main/geojson/china_province.geojson";
const OUTPUT = "apps/web/src/components/country-map-cn.generated.ts";

function ringArea(ring) {
  let area = 0;
  for (let index = 0; index < ring.length - 1; index += 1) {
    const [x1, y1] = ring[index];
    const [x2, y2] = ring[index + 1];
    area += x1 * y2 - x2 * y1;
  }
  return Math.abs(area) / 2;
}

function ringBounds(ring) {
  let minLongitude = Infinity;
  let maxLongitude = -Infinity;
  let minLatitude = Infinity;
  let maxLatitude = -Infinity;
  for (const [longitude, latitude] of ring) {
    minLongitude = Math.min(minLongitude, longitude);
    maxLongitude = Math.max(maxLongitude, longitude);
    minLatitude = Math.min(minLatitude, latitude);
    maxLatitude = Math.max(maxLatitude, latitude);
  }
  return { minLongitude, maxLongitude, minLatitude, maxLatitude };
}

function squaredSegmentDistance(point, start, end) {
  let x = start[0];
  let y = start[1];
  let dx = end[0] - x;
  let dy = end[1] - y;

  if (dx !== 0 || dy !== 0) {
    const t = ((point[0] - x) * dx + (point[1] - y) * dy) / (dx * dx + dy * dy);
    if (t > 1) {
      x = end[0];
      y = end[1];
    } else if (t > 0) {
      x += dx * t;
      y += dy * t;
    }
  }

  dx = point[0] - x;
  dy = point[1] - y;
  return dx * dx + dy * dy;
}

function simplifyDouglasPeucker(points, tolerance) {
  if (points.length <= 3) return points;
  const closed =
    points[0][0] === points.at(-1)[0] && points[0][1] === points.at(-1)[1];
  const source = closed ? points.slice(0, -1) : [...points];
  if (source.length <= 3) return points;

  const squaredTolerance = tolerance * tolerance;
  const keep = new Uint8Array(source.length);
  keep[0] = 1;
  keep[source.length - 1] = 1;
  const stack = [[0, source.length - 1]];

  while (stack.length > 0) {
    const [first, last] = stack.pop();
    let maxDistance = squaredTolerance;
    let index = -1;
    for (let candidate = first + 1; candidate < last; candidate += 1) {
      const distance = squaredSegmentDistance(source[candidate], source[first], source[last]);
      if (distance > maxDistance) {
        index = candidate;
        maxDistance = distance;
      }
    }
    if (index !== -1) {
      keep[index] = 1;
      stack.push([first, index], [index, last]);
    }
  }

  const simplified = source.filter((_, index) => keep[index] === 1);
  if (closed) simplified.push(simplified[0]);
  return simplified;
}

function roundRing(ring) {
  return ring.map(([longitude, latitude]) => [
    Number(longitude.toFixed(4)),
    Number(latitude.toFixed(4)),
  ]);
}

const response = await fetch(SOURCE_URL);
if (!response.ok) {
  throw new Error(`Failed to fetch China boundary: ${response.status} ${response.statusText}`);
}
const geojson = await response.json();
const coordinates = geojson?.features?.[0]?.geometry?.coordinates;
if (!Array.isArray(coordinates)) throw new Error("Unexpected China GeoJSON structure");

const rings = coordinates
  .map((polygon) => polygon?.[0])
  .filter((ring) => Array.isArray(ring) && ring.length >= 4)
  .map((ring) => ({ ring, bounds: ringBounds(ring), area: ringArea(ring) }));

const mainland = [...rings].sort((left, right) => right.area - left.area)[0];
if (!mainland) throw new Error("Mainland boundary ring not found");

// Keep Hainan as the only detached large island in the CN catalogue geometry.
// Taiwan remains a separate catalogue entry in Weather V2, and tiny South China
// Sea features are intentionally omitted so they do not crush the useful map scale.
const hainan = rings
  .filter(({ bounds }) =>
    bounds.minLongitude >= 108 &&
    bounds.maxLongitude <= 112 &&
    bounds.minLatitude >= 18 &&
    bounds.maxLatitude <= 21,
  )
  .sort((left, right) => right.area - left.area)[0];
if (!hainan) throw new Error("Hainan boundary ring not found");

const selected = [
  simplifyDouglasPeucker(mainland.ring, 0.12),
  simplifyDouglasPeucker(hainan.ring, 0.06),
].map(roundRing);

const bounds = selected.flat().reduce(
  (acc, [longitude, latitude]) => ({
    minLongitude: Math.min(acc.minLongitude, longitude),
    maxLongitude: Math.max(acc.maxLongitude, longitude),
    minLatitude: Math.min(acc.minLatitude, latitude),
    maxLatitude: Math.max(acc.maxLatitude, latitude),
  }),
  {
    minLongitude: Infinity,
    maxLongitude: -Infinity,
    minLatitude: Infinity,
    maxLatitude: -Infinity,
  },
);

const source = `// Generated by tooling/maps/generate-cn-geometry.mjs\n// Source: ${SOURCE_URL}\n// Source license: MIT (Supeset/China-GeoData)\n// Product note: retains mainland + Hainan only to preserve Weather V2's existing CN/TW catalogue split.\n\nexport const CHINA_MAP_BOUNDS = ${JSON.stringify(bounds, null, 2)} as const;\n\nexport const CHINA_MAP_RINGS = ${JSON.stringify(selected)} as const;\n`;

await mkdir(dirname(OUTPUT), { recursive: true });
await writeFile(OUTPUT, source, "utf8");
console.log(
  JSON.stringify({
    output: OUTPUT,
    sourcePoints: mainland.ring.length + hainan.ring.length,
    generatedPoints: selected[0].length + selected[1].length,
    bounds,
  }),
);
