export function listCuratedPois(cityId: string): ReadonlyArray<CuratedPoi> {
  return BY_CITY.get(cityId) ?? [];
}

export function findCuratedPoi(poiId: string): CuratedPoi | null {
  return POIS.find((item) => item.id === poiId) ?? null;
}

export function poiName(poi: CuratedPoi, locale: PoiLocale): string {
  return poi.name[locale];
}

export function findWeatherFallbacks(
  cityId: string,
  excludedPoiId: string | null,
  limit = 3,
): ReadonlyArray<CuratedPoi> {
  return listCuratedPois(cityId)
    .filter((item) => item.id !== excludedPoiId && item.environment === "indoor")
    .sort((left, right) => {
      const reservationWeight = (value: TripActivityReservation): number =>
        value === "none" ? 0 : value === "recommended" ? 1 : 2;
      const diff = reservationWeight(left.reservation) - reservationWeight(right.reservation);
      if (diff !== 0) return diff;
      return left.typicalDurationMinutes - right.typicalDurationMinutes;
    })
    .slice(0, Math.max(0, Math.min(limit, 5)));
}
