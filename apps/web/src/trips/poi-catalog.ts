import type {
  TripActivityCategory,
  TripActivityEnvironment,
  TripActivityReservation,
  TripWeatherSensitivity,
} from "./activity-intelligence";

export type PoiLocale = "en" | "zh-cn" | "zh-hant";

export interface CuratedPoi {
  readonly id: string;
  readonly cityId: string;
  readonly name: Record<PoiLocale, string>;
  readonly latitude: number;
  readonly longitude: number;
  readonly category: TripActivityCategory;
  readonly environment: TripActivityEnvironment;
  readonly weatherSensitivity: ReadonlyArray<TripWeatherSensitivity>;
  readonly typicalDurationMinutes: number;
  readonly reservation: TripActivityReservation;
  readonly recommendedWindow: "morning" | "afternoon" | "evening" | "any";
  readonly provenance: "curated-v1" | "openstreetmap-v1";
  readonly sourceRef?: string;
}

type PoiSeed = Omit<CuratedPoi, "provenance" | "weatherSensitivity"> & {
  readonly weatherSensitivity?: ReadonlyArray<TripWeatherSensitivity>;
};

function sensitivity(environment: TripActivityEnvironment): ReadonlyArray<TripWeatherSensitivity> {
  if (environment === "indoor") return [];
  if (environment === "mixed") return ["rain", "heat", "wind"];
  return ["rain", "heat", "cold", "wind", "uv"];
}

function poi(seed: PoiSeed): CuratedPoi {
  return {
    ...seed,
    weatherSensitivity: seed.weatherSensitivity ?? sensitivity(seed.environment),
    provenance: "curated-v1",
  };
}

